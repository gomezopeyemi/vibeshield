/* Legal document draft generators. These produce real, templated drafts from
 * the detected third-party APIs. They are DRAFTS requiring legal review — the UI
 * always labels them as such. No external service is contacted. */

const TODAY = () =>
  new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" });

const API_PURPOSE: Record<string, string> = {
  Stripe: "payment processing and subscription billing",
  OpenAI: "AI-generated content and features",
  Anthropic: "AI-generated content and features",
  PostHog: "product analytics and usage measurement",
  Supabase: "authentication and database storage",
  Resend: "transactional email delivery",
  ElevenLabs: "audio and voice generation",
  Replicate: "AI model inference",
};

export function generatePrivacyPolicy(apis: string[]): string {
  const subs = apis
    .map((a) => `- **${a}** — ${API_PURPOSE[a] ?? "third-party service integration"}`)
    .join("\n");
  return `# Privacy Policy

_Last updated: ${TODAY()}_

> DRAFT — generated by VibeShield from your detected integrations. Have it reviewed by a qualified professional before publishing.

## 1. Information we collect
We collect information you provide (such as your account email) and information generated as you use the product (such as usage events and content you create).

## 2. How we use information
We use your information to operate, maintain and improve the product, to communicate with you, and to secure the service.

## 3. Third-party sub-processors
This application shares limited data with the following services to function:
${subs}

Each sub-processor only receives the data necessary for its purpose.

## 4. Data retention
We retain personal data for as long as your account is active or as needed to provide the service, then delete or anonymize it.

## 5. Your rights
Depending on your location, you may have rights to access, correct, export or delete your personal data. See "Delete my account" for GDPR deletion.

## 6. Contact
Questions about this policy can be directed to privacy@your-domain.com.`;
}

