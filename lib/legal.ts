export function generateGdprEndpoint(): string {
  return `// app/api/account/delete/route.ts
// GDPR "Delete my account" endpoint — DRAFT. Review and test before shipping.
import { createClient } from "@/lib/supabase/server";

export async function POST() {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return new Response("Unauthorized", { status: 401 });

  // 1) Delete or anonymize user-owned rows (respect FKs and retention rules).
  await supabase.from("profiles").delete().eq("user_id", user.id);
  await supabase.from("orders").delete().eq("user_id", user.id);

  // 2) Delete the auth user (requires a server-side admin client).
  await supabaseAdmin.auth.admin.deleteUser(user.id);

  // 3) Confirm deletion to the user (e.g. email receipt).
  return Response.json({ deleted: true });
}`;
}
